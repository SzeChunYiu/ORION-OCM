def measure_bytes(obj) -> int:
    """Persistent/active byte measure: canonical JSON length of the object's serial form."""
    import json
    return len(json.dumps(obj, sort_keys=True, default=_json_default).encode("utf-8"))


def _json_default(o):
    if isinstance(o, frozenset):
        return sorted(str(x) for x in o)
    if isinstance(o, (set, tuple)):
        return list(o)
    return str(o)


def field_snapshot(ks: KnowledgeSpace) -> Dict[str, object]:
    return {"atoms": [a.as_dict() for a in ks.atoms],
            "edges": [e.as_dict() for e in ks.hyperedges]}
