"""Tests for #833 Section Z, Z13 rows 9-10 / Z16 chain (frozen prediction Z13-P3).

Runs under `python3 -I -B` and `python3 -I -O -B`; every check raises
explicitly so `-O` cannot strip it. Stdlib only. The receipts are read from
disk (regenerated by the routes if absent); the workflow regenerates them
first and then requires them byte-identical to the committed ones.
"""
import json
import os
import subprocess
import sys
import unittest
from fractions import Fraction as F

HERE = os.path.dirname(os.path.abspath(__file__))
A_PY = os.path.join(HERE, "z13_repaired_chain_v1.py")
B_PY = os.path.join(HERE, "independent_z13_oracle_v1.py")
RES = os.path.join(HERE, "RESULT_V1.json")
ORA = os.path.join(HERE, "ORACLE_RESULT_V1.json")
FREEZE = os.path.join(HERE, "FREEZE_V1.md")
AMEND = os.path.join(HERE, "FREEZE_V1_AMENDMENT_1.md")
REG = os.path.join(HERE, "FAILED_PREDICTION_REGISTER_V1.json")
PKG = "research/gmi-833-z-z13-repaired-chain-v1"


def need(c, m):
    if not c:
        raise AssertionError(m)


def load(path, regen):
    if not os.path.exists(path):
        r = subprocess.run([sys.executable, "-I", "-B", regen], stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        need(r.returncode == 0, "%s failed: %s" % (regen, r.stderr.decode()[-2000:]))
    with open(path) as fh:
        return json.load(fh)


def git(*args):
    repo = os.path.dirname(os.path.dirname(HERE))
    try:
        r = subprocess.run(["git", "-C", repo] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode != 0:
        return None
    return r.stdout.decode().strip()


class Z13P3(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.a = load(RES, A_PY)
        cls.b = load(ORA, B_PY)
        with open(REG) as fh:
            cls.reg = json.load(fh)

    # ------------------------------------------------------------ verdicts
    def test_01_both_routes_hit_every_named_axis(self):
        for route in (self.a, self.b):
            need(route["verdict"] == "HIT", "verdict %r" % route["verdict"])
            for L in ("5", "6"):
                for k, v in route["hit_conditions"][L].items():
                    need(v is True, "%s route %s L=%s not hit" % (k, route["route"], L))

    def test_02_routes_agree_on_every_floor_and_argmin(self):
        for L in ("5", "6"):
            need(self.a["per_L"][L]["floors"] == self.b["per_L"][L]["floors"],
                 "floors differ at L=%s: %r vs %r" % (L, self.a["per_L"][L]["floors"], self.b["per_L"][L]["floors"]))
            need(self.a["per_L"][L]["d2_b1_floor_attaining_next_state_functions"] ==
                 [list(x) for x in self.b["per_L"][L]["d2_b1_floor_attaining_next_state_functions"]] or
                 self.a["per_L"][L]["d2_b1_floor_attaining_next_state_functions"] ==
                 self.b["per_L"][L]["d2_b1_floor_attaining_next_state_functions"], "argmin lists differ at L=%s" % L)
            need(self.a["per_L"][L]["per_t_copy_reset"] == self.b["per_L"][L]["per_t_copy_reset"], "per-t errors differ")
            need(self.a["per_L"][L]["copy_then_set_d2_error"] == self.b["per_L"][L]["copy_then_set_d2_error"], "set-variant error differs")
            need(self.a["per_L"][L]["nonempty_niches"] == self.b["per_L"][L]["nonempty_niches"] == "96/135", "niche counts")
            need(self.a["per_L"][L]["collapse_coefficient_4R_minus_1"] == self.b["per_L"][L]["collapse_coefficient_4R_minus_1"], "coefficient")

    def test_03_frozen_numbers_exactly(self):
        need(self.a["per_L"]["5"]["floors"]["b1_m2"] == "5/16", "L5 floor")
        need(self.a["per_L"]["6"]["floors"]["b1_m2"] == "41/128", "L6 floor")
        need(self.a["per_L"]["5"]["copy_then_set_d2_error"] == "17/48", "P3-e")
        need(self.a["per_L"]["5"]["collapse_coefficient_4R_minus_1"] == "1/4", "L5 coefficient")
        need(self.a["per_L"]["6"]["collapse_coefficient_4R_minus_1"] == "9/32", "L6 coefficient")
        need(self.a["per_L"]["5"]["per_t_copy_reset"] == {"2": "1/4", "3": "3/8", "4": "5/16"}, "per-t L5")
        need(self.a["per_L"]["6"]["per_t_copy_reset"] == {"2": "1/4", "3": "3/8", "4": "5/16", "5": "11/32"}, "per-t L6")
        for L in ("5", "6"):
            need(self.a["per_L"][L]["d2_b1_floor_attaining_next_state_functions"] == [[0, 1, 0, 0], [1, 0, 0, 0]], "argmin pair")

    def test_04_probe_table_and_flip_world_on_both_routes(self):
        expect = {"5": {"flip": True, "boundary": True, "control_never_flips": True, "control_always_empty": False, "retired_ecology_p2_zero": True},
                  "6": {"flip": False, "boundary": False, "control_never_flips": True, "control_always_empty": False, "retired_ecology_p2_zero": True}}
        for route in (self.a, self.b):
            for L in ("5", "6"):
                rows = dict((r["probe"], r) for r in route["per_L"][L]["probes"])
                for name, ne in expect[L].items():
                    for cell in rows[name]["by_eta"]:
                        need(cell["niche_nonempty"] is ne, "%s L=%s eta=%s route %s" % (name, L, cell["eta"], route["route"]))
        # the flip world has strictly negative width at L = 6 and positive at L = 5 (Route A endpoints)
        rows6 = dict((r["probe"], r) for r in self.a["per_L"]["6"]["probes"])
        rows5 = dict((r["probe"], r) for r in self.a["per_L"]["5"]["probes"])
        for c in rows6["flip"]["by_eta"]:
            need(F(c["width"]) < 0, "flip world width at L=6 not negative: %s" % c["width"])
        for c in rows5["flip"]["by_eta"]:
            need(F(c["width"]) > 0, "flip world width at L=5 not positive: %s" % c["width"])
        for c in rows6["boundary"]["by_eta"]:
            need(F(c["width"]) == 0, "boundary world width at L=6 not zero")

    def test_05_lemmas_reverified_by_route_b_before_use(self):
        lm = self.b["lemmas_L5"]
        need(lm["majority_optimality"]["holds"] is True and lm["majority_optimality"]["pairs_checked"] == 51, "majority optimality")
        need(lm["mode_independence"]["b1"]["holds"] is True and lm["mode_independence"]["b1"]["joint_candidates"] == 16777216, "mode independence b=1")
        need(lm["mode_independence"]["b0"]["holds"] is True, "mode independence b=0")

    # ------------------------------------------------------------ hostiles / null / vacuity
    def test_06_hostiles_applicable_and_moved(self):
        h = self.a["hostiles"]
        need(len(self.a["hostiles_applicable"]) >= 7, "fewer than 7 applicable hostiles")
        for k in self.a["hostiles_applicable"]:
            need(h[k]["moved"] is True, "applicable hostile %s did not move" % k)
        need(self.a["hostiles_vacuous"] == ["H7_L4_window_on_L5"], "vacuous set %r" % self.a["hostiles_vacuous"])
        need(h["H7_L4_window_on_L5"]["d2_b1_floor"] == h["H7_L4_window_on_L5"]["true"] == "5/16", "vacuity reason")
        need(h["H7_L4_window_on_L6"]["moved"] is True, "window hostile at L=6")
        need(self.a["hostiles_all_moved"] is True, "hostiles_all_moved")

    def test_07_no_alarm_control_silent(self):
        need(self.a["no_alarm_control"]["silent_as_required"] is True, "no-alarm control fired")

    def test_08_nulls_beaten_with_true_law_excluded_from_pool(self):
        n1 = self.a["null_upper_endpoint_L6"]
        need(n1["perfect"] == 0 and n1["marginal_score"] == "135/135" and n1["trials"] == 200, "null 1")
        need("minus the marginal pair" in n1["pool"], "null 1 pool includes the true pair")
        n2 = self.a["null_collapse_rule_L6"]
        need(n2["perfect"] == 0 and n2["predicted_score"] == "156/156" and n2["trials"] == 200, "null 2")
        need("minus the predicted coefficient" in n2["pool"], "null 2 pool includes the true coefficient")
        need(self.a["null_discriminating_worlds_prediction_hit"] is True, "amendment prediction on the discriminating worlds")
        # the first-frozen null-2 outcome is recorded, not erased
        f = self.a["null_collapse_rule_L6_as_first_frozen"]
        need(f["perfect"] == 9 and f["status"].startswith("MISS"), "first-frozen null 2 record")
        need(any(e["id"] == "NULL2-UNIQUENESS-CLAUSE" for e in self.reg["entries"]), "register lacks the null-2 clause entry")

    def test_09_discriminating_worlds_agree_across_routes(self):
        a = dict((w["name"], w) for w in self.a["null_collapse_rule_L6"]["null_discriminating_worlds"])
        b = dict((w["world"], w) for w in self.b["per_L"]["6"]["null_discriminating_worlds"])
        for name in a:
            for ca, cb in zip(a[name]["by_eta"], b[name]["by_eta"]):
                need(ca["niche_nonempty_L6"] == cb["niche_nonempty"], "discriminating world %s disagrees" % name)

    def test_10_vacuity_both_sides(self):
        v = self.a["vacuity"]
        need(v["every_bound_has_both_sides"] is True and v["probes_both_outcomes_each_L"] is True, "vacuity")
        need(v["L5_nonempty_vs_empty"] == ["96/135", "39/135"] and v["L6_nonempty_vs_empty"] == ["96/135", "39/135"], "counts")

    # ------------------------------------------------------------ custody
    def test_11_freeze_text_pins_the_numbers_before_the_run(self):
        with open(FREEZE, encoding="utf-8") as fh:
            fz = fh.read()
        for s in ("`5/16` at `L = 5`", "`41/128` at `L = 6`", "`96` of `135`", "`(0, 17/81, 64/81)`", "`9/32` at", "`17/48` at `L = 5`"):
            need(s in fz, "freeze does not pin %r" % s)
        need(os.path.exists(AMEND), "amendment missing")

    def test_12_custody_chain_freeze_precedes_receipts(self):
        """Freeze commit -> amendment commit -> receipt commit, by git order.
        Falls back to a distinct UNREACHABLE state when git history is absent
        (shallow clone, squash); never passes silently."""
        first = git("log", "--format=%H", "--reverse", "--", PKG + "/FREEZE_V1.md")
        rec = git("log", "--format=%H", "--reverse", "--", PKG + "/RESULT_V1.json")
        if not first or not rec:
            sys.stderr.write("custody: UNREACHABLE (no git history for the package)\n")
            need(os.path.exists(FREEZE) and os.path.getsize(FREEZE) > 1000, "frozen bytes absent")
            return
        fz = first.split("\n")[0]
        rc = rec.split("\n")[0]
        if fz == rc:
            files = git("show", "--pretty=format:", "--name-only", fz)
            need(files is not None and PKG + "/FREEZE_V1.md" in files, "squash: freeze absent from the publishing commit")
            return
        anc = subprocess.run(["git", "-C", os.path.dirname(os.path.dirname(HERE)), "merge-base", "--is-ancestor", fz, rc]).returncode
        need(anc == 0, "freeze commit does not precede the receipt commit")
        am = git("log", "--format=%H", "--reverse", "--", PKG + "/FREEZE_V1_AMENDMENT_1.md")
        if am:
            a0 = am.split("\n")[0]
            if a0 != rc:
                anc = subprocess.run(["git", "-C", os.path.dirname(os.path.dirname(HERE)), "merge-base", "--is-ancestor", a0, rc]).returncode
                need(anc == 0, "amendment does not precede the receipt commit")


if __name__ == "__main__":
    unittest.main()
