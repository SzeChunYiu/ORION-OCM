#: Cost to check whether a held rule actually generates a given answer.  Cheaper
#: than deriving and dearer than applying, so that checking is a real decision
#: rather than a free action or an unaffordable one.
VERIFY_COST: int = 25

#: Cost to combine two answers once both are in hand.  Charged to every arm
#: identically, so it cannot separate them; it is here because a composition
#: that costs nothing is not a composition.
COMPOSE_COST: int = 5

#: Fraction of answers that are EXCEPTIONS: inside a rule's nominal extension and
#: not generated by it.  An arm applying the rule to one of these is WRONG.
EXCEPTION_RATE: float = 0.10

#: Bits to hold one composite rule.  A composite names two base rules and the
#: way they combine, so it is dearer than either.
COMPOSITE_BITS: int = 48


