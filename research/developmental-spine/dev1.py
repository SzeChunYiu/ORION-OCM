@dataclass(frozen=True)
class Pair:
    """One D1 demand: two answers from two different rules, to be combined."""

    left: int
    right: int


@dataclass(frozen=True)
class D1World:
    """D0's world, plus the exceptions that make scope a real question."""

    base: World
    #: Answers that are inside a rule's nominal extension and NOT generated by it.
    exceptions: frozenset[int]

    @property
    def rule_of(self) -> tuple[int, ...]:
        return self.base.rule_of

    @property
    def members(self) -> tuple[tuple[int, ...], ...]:
        return self.base.members

    @property
    def rule_count(self) -> int:
        return self.base.rule_count

    def generated_by_rule(self, answer: int) -> bool:
        """False for exceptions: applying a rule to one of these gives a wrong answer."""
        return answer not in self.exceptions


def build_d1_world(rule_count: int, extension: int, rate: float,
                   rng: random.Random) -> D1World:
    base = build_world(rule_count, extension)
    exceptions = set()
    for r in range(rule_count):
        for f in base.members[r]:
            if rng.random() < rate:
                exceptions.add(f)
    return D1World(base, frozenset(exceptions))


def d1_stream(world: D1World, horizon: int, skew: float,
              rng: random.Random) -> tuple[Pair, ...]:
    """Pairs drawn from two DIFFERENT rules, so every D1 demand is a composition."""
    singles = demand_stream(world.base, horizon * 2, skew, rng)
    out: list[Pair] = []
    i = 0
    while len(out) < horizon and i + 1 < len(singles):
        a, b = singles[i], singles[i + 1]
        if world.rule_of[a] != world.rule_of[b]:
            out.append(Pair(a, b))
            i += 2
        else:
            i += 1
    while len(out) < horizon:
        a = rng.randrange(world.base.answers)
        b = rng.randrange(world.base.answers)
        if world.rule_of[a] != world.rule_of[b]:
            out.append(Pair(a, b))
    return tuple(out)
