"""DEV-1: one real D0 to D1 transition, in the only economy where carrying state can pay.

Issue #151 asks for a persistent OCM lineage that carries earned competence
across developmental stages, and asks the one question that makes such a claim
developmental rather than merely cumulative:

    the decisive question is not whether the older machine scores higher, it is
    whether prior developmental experience causally made the next competence
    cheaper

``spine.py`` reported that the repository supported ZERO complete transitions.
This module builds the first one.  It can only be built now, and the reason
matters more than the build: until E10 (``research/cognitive-ladder/retain.py``)
every world in this programme gave retention away for free and without bound,
and in such a world the optimal policy is provably to carry nothing.  A
developmental lineage measured there is a lineage whose central proposition is
arithmetically excluded before the first episode runs.  E10 bounded retention in
bits and priced it, and the sign of the comparison reversed.  DEV-1 is that
economy with a developmental boundary drawn through it.

The two stages
--------------

``D0`` -- *basic exact interaction*.  A stream of single demands.  Serve each
one exactly.  This is E10's world and the D0 arms behave exactly as E10's arms
did, which is deliberate: the D0 phase must not be a new experiment quietly
smuggled in as a premise.

``D1`` -- *composition, failure and scope*.  Three things D0 never asked for:

    COMPOSITION   a demand for a pair drawn from two different rules, which must
                  both be answered and then combined.  Composition depth 2.
    SCOPE         some pair members are EXCEPTIONS: answers that look like they
                  belong to a rule's extension and are not generated by it.  An
                  arm that applies a held rule without checking gets the answer
                  WRONG.
    FAILURE       an arm may pay ``VERIFY_COST`` to check scope before applying,
                  or refuse to apply and derive instead.

Scope is what stops this from being a caching experiment with extra steps.  In
D0 every arm was correct by construction and work was the only free coordinate.
In D1 correctness is a coordinate again, and it moves in the direction that is
DANGEROUS for the hypothesis: carrying rules from D0 is what creates the
opportunity for harmful transfer.  The arm with the most prior competence has
the most ways to be confidently wrong, and the receipt reports negative transfer
and harmful-transfer refusals as first-class fields rather than as caveats.

The four arms DEV-D8 requires
-----------------------------

``CONTINUED_OCM``          runs D0, keeps its store, runs D1.
``RESET_OCM``              runs D0, DISCARDS its store, runs D1.  Identical
                           architecture, identical D1 information.  It is the
                           only control that separates "prior experience made
                           this cheaper" from "D1 is just cheap".
``STRONG_ADAPTIVE_PARENT`` sees D0 and D1 concatenated AND the entire future,
                           and keeps the mixed instance/rule set that a
                           clairvoyant would keep.  Strictly more information
                           than the lineage, on purpose.
``TASK_SPECIFIC_OCM``      never sees D0 and never learns base rules; it acquires
                           COMPOSITE rules directly from D1, which is what a
                           system built for this stage alone would do.  It bounds
                           how much of any CONTINUED gain is generality rather
                           than a head start on the right objects.

What is reported, and what would refute it
------------------------------------------

Two work figures, never one:

    D1_ONLY     the developmental question -- given the lineage exists, is the
                next competence cheaper?
    LIFETIME    D0 + D1 -- did the lineage pay for itself?

A machine can win the first and lose the second, and if it does, that is the
result and it is reported as the result.  ``cheaper_because`` is a required
field: the D1 saving must be attributable to identified reused objects with
execution witnesses, not merely correlated with having a store.

The kill criterion is registered before execution: if ``CONTINUED_OCM`` does not
beat ``RESET_OCM`` on D1-only work at matched correctness, there is no D0 to D1
transition here, and the first entry in the developmental spine is a refusal.
"""

