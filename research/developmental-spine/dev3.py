#: Bits to hold a guard alongside its rule.  A guard names a period and a phase,
#: so it is small and constant -- and it is charged against the SAME budget the
#: replay parent spends on answers, which is what makes the comparison fair. Two
#: fact-slots: a guarded rule costs RULE_BITS + GUARD_BITS = six answer slots.
GUARD_BITS: int = 16

#: The guard language: ``index % period == phase``, plus the empty guard.
GUARD_PERIODS: tuple[int, ...] = (2, 3, 4, 5)


@dataclass(frozen=True)
class Guard:
    """``None`` period means 'this rule has no exceptions'."""

    period: int | None
    phase: int

    def excludes(self, index: int) -> bool:
        return self.period is not None and index % self.period == self.phase


def guard_candidates() -> tuple[Guard, ...]:
    out = [Guard(None, 0)]
    for period in GUARD_PERIODS:
        for phase in range(period):
            out.append(Guard(period, phase))
    return tuple(out)


def build_structured_world(rule_count: int, extension: int,
                           rng: random.Random) -> tuple[D1World, dict[int, Guard]]:
    base = build_world(rule_count, extension)
    truth: dict[int, Guard] = {}
    exceptions: set[int] = set()
    for r in range(rule_count):
        period = rng.choice(GUARD_PERIODS + (None,))
        phase = rng.randrange(period) if period else 0
        guard = Guard(period, phase)
        truth[r] = guard
        for index, answer in enumerate(base.members[r]):
            if guard.excludes(index):
                exceptions.add(answer)
    return D1World(base, frozenset(exceptions)), truth


def build_random_world(rule_count: int, extension: int, exception_count: int,
                       rng: random.Random) -> tuple[D1World, dict[int, Guard]]:
    """Exactly ``exception_count`` exceptions, placed at random.

    The count is MATCHED to the structured world of the same replicate rather
    than drawn from a rate. Without that the two regimes would differ in how
    MANY exceptions there are as well as in whether they have structure, and a
    sign change could be attributed to the rate -- the structured draw produces
    about 35 per cent exceptions against an independent rate's 11, so the
    confound is large and in the direction that would have flattered the guard.
    """
    base = build_world(rule_count, extension)
    answers = [a for r in range(rule_count) for a in base.members[r]]
    rng.shuffle(answers)
    return D1World(base, frozenset(answers[:exception_count])), {}


