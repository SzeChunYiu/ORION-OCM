"""Guarded rules: paying bits instead of a check, and the condition under which that works.

This module is ``DEV-3``.  It exists because ``DEV2_CONTINUAL_PARENTS_V1`` did
not merely beat the lineage, it said exactly why, by pricing the reason:

    a held rule licenses a scope CHECK, never an answer, so using one costs
    VERIFY + APPLY where a stored answer costs LOOKUP.  Sweeping the check price
    on identical worlds flips the sign between 10 and 25, with replay's own work
    constant throughout.  Rules are cheaper to ACQUIRE and much dearer to USE.

The tempting response is to make the check cheap and declare a win.  That is
precisely what publication constitution section 11 forbids -- making the
environment one in which explicit reuse is optimal by construction -- and the
sweep in DEV-2 already reports what happens at every check price, so nothing
would be learned by fixing one.

The principled response is a REPRESENTATION change: a rule that carries its own
scope precondition.  A guarded rule costs more BITS and no per-use check.  It
competes for the same budget against the same replay parent, so if it wins it
wins by being a better thing to hold, not by being charged less to hold it.

The reason this might be impossible, stated before it is attempted
-----------------------------------------------------------------

A guard is only useful if it is SOUND: an arm that skips verification on the
strength of a guess is not cheaper, it is wrong, and the capability gate throws
it out.  And in DEV-1's world, soundness looks unaffordable:

    exceptions are drawn independently per answer, so the only sound guard is
    the exception LIST, and learning that list requires deriving every member of
    the extension -- which costs exactly what memoizing the extension costs

If that is the whole story then guarded rules cannot win here, and DEV-3's
result is an impossibility rather than an experiment.  That would be worth
reporting, and it is registered as a possible outcome rather than discovered as
a disappointment.

What makes it a question rather than a theorem is that the argument depends on
the exceptions being STRUCTURELESS.  If exceptions are generated by a rule of
their own, the guard is a small predicate rather than a list, and it is learnable
from a few observations.  So the experiment is not "do guards work" -- it is:

    **a guard pays exactly when the exception set is itself compressible**

which is the same condition the acquired structure had to meet, applied one level
up.  That recursion is the interesting claim and it is the one under test.

The two exception regimes
-------------------------

``RANDOM``      exceptions are placed at random, in EXACTLY the number the
                structured world of the same replicate has.  No predicate in the
                guard language covers them, the version space empties, and the
                arm must fall back to verifying every application.  This regime
                is the ANTI-RIGGING CONTROL: it must reproduce DEV-2's result,
                with replay beating the lineage. If it does not, the harness is
                not DEV-1's and the run is void.  Matching the COUNT rather than
                a rate matters: the structured draw yields about 35 per cent
                exceptions and an independent 10 per cent rate yields 11, so an
                unmatched control would have let a rate difference masquerade as
                a structure effect, in the direction that flatters the guard.
``STRUCTURED``  exceptions are the answers whose within-rule index satisfies
                ``index % period == phase``, for a period and phase drawn per
                rule.  The guard language contains this family, so a sound guard
                exists and is small.

Soundness without a gift
------------------------

The arm is NOT told which regime it is in and is not told any rule's guard.  It
holds a version space over the guard language and may skip verification only
when that version space is a SINGLETON.  Since the truth is always consistent
with the observations, a singleton version space provably contains the truth, so
skipping is sound rather than lucky, and correctness stays at 1.0 by
construction rather than by hope.  Under RANDOM exceptions the version space
empties instead, the arm detects that it has no guard and verifies for ever,
which is the honest failure mode and is also how it reproduces DEV-2.

The gift that IS taken, declared: the guard language contains the truth in the
STRUCTURED regime.  This is the same gift E6 declared when it gave each method
its candidate evidence set -- which predicate is right is discovered, that the
right one is expressible is given.  A world where the guard language must also
be learned is a different and larger experiment, and it can only make the arm's
position worse.
"""

