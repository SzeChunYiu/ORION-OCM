class BayesOrdered(Row):
    """the D3 parent with an explicit order variable: (marginal, two conditionals) per pair per order."""
    row = "BAYES_ORDERED"

    def _fit_cond(self, M, a, target):
        """division-free charged binary search for u minimising |a*u - target|, u in [0, S]."""
        A = self.A; lo, hi = 0, A.S
        for _ in range(A.S.bit_length()):
            mid = (lo + hi) // 2
            if A.gt(target, A.mul(a, mid)): lo = mid
            else: hi = mid
            self.native[0] += 1
        return lo if abs(A.mul(a, lo) - target) <= abs(A.mul(a, hi) - target) else hi

    def learn(self, M):
        A = self.A; self.par = []
        for t in self.e["table"]:
            s = [A.from_units(x) for x in t]
            a = A.add(s[0], s[1]); b = A.add(s[4], s[5])
            u = self._fit_cond(M, a, s[0]); v = self._fit_cond(M, A.sub(A.S, a), s[2])
            x = self._fit_cond(M, b, s[4]); y = self._fit_cond(M, A.sub(A.S, b), s[6])
            self.par.append((a, u, v, b, x, y))

    def answer(self, M, q, idx):
        A = self.A; a, u, v, b, x, y = self.par[q]
        self.native[0] += 1
        if idx == 0: return A.to_units(A.mul(a, u))
        if idx == 1: return A.to_units(A.mul(a, A.sub(A.S, u)))
        if idx == 2: return A.to_units(A.mul(A.sub(A.S, a), v))
        if idx == 3: return A.to_units(A.mul(A.sub(A.S, a), A.sub(A.S, v)))
        if idx == 4: return A.to_units(A.mul(b, x))
        if idx == 5: return A.to_units(A.mul(b, A.sub(A.S, x)))
        if idx == 6: return A.to_units(A.mul(A.sub(A.S, b), y))
        return A.to_units(A.mul(A.sub(A.S, b), A.sub(A.S, y)))

    def desc_bits(self): return self.e["Q"] * 6 * PROB_BITS


class TableRow(Row):
    """the D2 parent: memorize all 8Q registered numbers at the instrument's resolution; charged linear scan."""
    row = "TABLE"

    def learn(self, M):
        A = self.A
        self.mem = [[(q, i, A.from_units(v)) for i, v in enumerate(t)] for q, t in enumerate(self.e["table"])]

    def answer(self, M, q, idx):
        A = self.A
        for entries in self.mem:
            for (qq, ii, v) in entries:
                if M.op("EQ", qq * 8 + ii, q * 8 + idx):
                    self.native[0] += 1
                    return A.to_units(v)
        self.native[0] += 1
        return 0

    def desc_bits(self): return self.e["Q"] * 8 * PROB_BITS


