def run(row, basis, eco, seed=0, precision="wide"):
    M = Machine(basis, seed=seed); A = QArith(M, precision); ref = ROWS[row](eco, A)
    M.phase("exec"); ref.init(M)
    M.phase("upd"); ref.learn(M); M.end_event()
    learn = dict(M.L.c); learn_native = ref.native[0]
    M.phase("exec"); ok = 0; outs = []; served = []
    for q in range(eco["Q"]):
        for i in range(8):
            v = ref.answer(M, q, i); served.append(v); outs.append((q, i, v))
            ok += int(abs(v - eco["table"][q][i]) <= TOL_UNITS)
    nq = 8 * eco["Q"]
    cap = round(ok / nq, 4)
    R = dict(M.L.c)
    qq = [qq_residual(served[8 * q:8 * q + 8]) for q in range(eco["Q"])]
    return {"row": row, "basis": basis.name, "precision": precision, "capability": cap, "admissible": cap >= THETA,
            "R": R, "learn_ops": learn["upd"], "exec_per_query": (R["exec"] - learn["exec"]) / nq,
            "native_ops": ref.native[0] - learn_native, "native_per_query": (ref.native[0] - learn_native) / nq,
            "learn_native_ops": learn_native, "desc_bits": ref.desc_bits(), "n_queries": nq,
            "max_abs_error_units": max(abs(v - eco["table"][q][i]) for q in range(eco["Q"]) for i, v in enumerate(served[8 * q:8 * q + 8])),
            "qq_residual_units_served": qq, "max_abs_qq_served": max(abs(x) for x in qq),
            "answer_signature": sha256_of(outs)}


