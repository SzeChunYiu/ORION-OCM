# declared high-precision pi: floor(pi * 10^50) over 10^50
PI_NUM = 314159265358979323846264338327950288419716939937510
PI_DEN = 10 ** 50


def _cos_w(a, b):
    """cos(a*pi/b) at the declared working scale PI_DEN, by integer Taylor series (a >= 0, 0 <= a/b <= 1)."""
    x = PI_NUM * a // b
    mag = PI_DEN; total = PI_DEN; sign = 1; k = 1
    while mag and k < 80:
        mag = mag * x // PI_DEN * x // PI_DEN // ((2 * k - 1) * (2 * k))
        sign = -sign; total += sign * mag; k += 1
    return total


def _sin_w(a, b):
    """sin(a*pi/b) = cos(|b - 2a| * pi / (2b)) at the declared working scale."""
    return _cos_w(abs(b - 2 * a), 2 * b)


def _quant(val_w, S):
    """round a value at working scale PI_DEN to the instrument scale S (round half away from zero)."""
    neg = val_w < 0; v = -val_w if neg else val_w
    q = (v * S + PI_DEN // 2) // PI_DEN
    return -q if neg else q


def cos_q(g, S): return _quant(_cos_w(g, G_ANGLES), S)


def sin_q(g, S): return _quant(_sin_w(g, G_ANGLES), S)


class QArith:
    """two declared precision instruments with IDENTICAL charged operation sequences.
      fx8 : the registered 8-bit fixed point (scale FX_ONE = 16, clamp at +-127 raw);
      wide: a declared wide fixed point at scale 2^WIDE_BITS evaluated at unbounded integer precision."""

    def __init__(self, M, mode):
        self.M = M; self.mode = mode
        self.S = FX_ONE if mode == "fx8" else (1 << WIDE_BITS)

    def mul(self, a, b):
        if self.mode == "wide":
            self.M.op("MUL", 0, 0)
            p = a * b; neg = p < 0; p = -p if neg else p
            r = (p + (self.S >> 1)) >> WIDE_BITS
            return -r if neg else r
        return self.M.op("MUL", a, b)

    def add(self, a, b):
        if self.mode == "wide": self.M.op("ADD", 0, 0); return a + b
        return self.M.op("ADD", a, b)

    def sub(self, a, b):
        if self.mode == "wide": self.M.op("SUB", 0, 0); return a - b
        return self.M.op("SUB", a, b)

    def gt(self, a, b):
        if self.mode == "wide": self.M.op("GT", 0, 0); return int(a > b)
        return self.M.op("GT", a, b)

    def to_units(self, v):
        """convert an instrument-scale value to the registered table's 4096ths (uncharged readout convention)."""
        neg = v < 0; u = -v if neg else v
        r = (u * PROB_UNITS + self.S // 2) // self.S
        return -r if neg else r

    def from_units(self, u):
        neg = u < 0; v = -u if neg else u
        r = (v * self.S + PROB_UNITS // 2) // PROB_UNITS
        return -r if neg else r


# ------------------------------------------------------------------------------------- declared projective model
def _rot(A, d, g, i, j):
    """a plane rotation matrix at the instrument scale (charged: only the two trig entries are placed)."""
    S = A.S
    m = [[S if p == q else 0 for q in range(d)] for p in range(d)]
    c, s = cos_q(g, S), sin_q(g, S)
    m[i][i] = c; m[j][j] = c; m[i][j] = -s; m[j][i] = s
    return m


def _matmul(A, X, Y, d):
    out = [[0] * d for _ in range(d)]
    for i in range(d):
        for j in range(d):
            acc = 0
            for k in range(d): acc = A.add(acc, A.mul(X[i][k], Y[k][j]))
            out[i][j] = acc
    return out


def _frame(A, d, g, planes):
    U = [[A.S if p == q else 0 for q in range(d)] for p in range(d)]
    for (i, j) in planes: U = _matmul(A, U, _rot(A, d, g, i, j), d)
    return U


PLANES_A = {2: [(0, 1)], 4: [(0, 2), (1, 3)]}
PLANES_B = {2: [(0, 1)], 4: [(0, 1), (2, 3)]}
PLANES_STATE = {2: [(0, 1)], 4: [(0, 1), (1, 2), (2, 3)]}
KEEP_A = {2: (0,), 4: (0, 1)}
KEEP_B_COMMUTING = {2: (1,), 4: (0, 2)}


def _proj(A, U, keep, d):
    """P = sum_{k in keep} u_k u_k^T where u_k is the k-th COLUMN of U (charged)."""
    P = [[0] * d for _ in range(d)]
    for i in range(d):
        for j in range(d):
            acc = 0
            for k in keep: acc = A.add(acc, A.mul(U[i][k], U[j][k]))
            P[i][j] = acc
    return P


def _complement(A, P, d):
    return [[(A.S if i == j else 0) - P[i][j] for j in range(d)] for i in range(d)]


def _state(A, d, g):
    U = _frame(A, d, g, PLANES_STATE[d])
    return [U[i][0] for i in range(d)]


def _matvec(A, P, v, d, native):
    out = []
    for i in range(d):
        acc = 0
        for j in range(d): acc = A.add(acc, A.mul(P[i][j], v[j]))
        out.append(acc)
    native[0] += 1  # one PROJECT at the declared native price
    return out


def _norm2(A, v, d, native):
    acc = 0
    for i in range(d): acc = A.add(acc, A.mul(v[i], v[i]))
    native[0] += 1  # one Born readout at the declared native price
    return acc


def joint_probs(A, d, psi, PA, PB, native):
    """the eight joint probabilities: order AB then order BA, each (yes yes, yes no, no yes, no no), in table units."""
    nA = _complement(A, PA, d); nB = _complement(A, PB, d)
    out = []
    for (M1, M1c, M2, M2c) in ((PA, nA, PB, nB), (PB, nB, PA, nA)):
        for a_yes in (True, False):
            v = _matvec(A, M1 if a_yes else M1c, psi, d, native)
            for b_yes in (True, False):
                w = _matvec(A, M2 if b_yes else M2c, v, d, native)
                out.append(A.to_units(_norm2(A, w, d, native)))
    return out  # [AyBy, AyBn, AnBy, AnBn, ByAy, ByAn, BnAy, BnAn]


def single_prob(A, d, psi, ops, idx, native):
    """ONE ordered joint probability from PRE-COMPILED projector matrices: two Lueders applications and one Born
    readout (2 matvecs + 1 norm), i.e. the serve cost the candidate actually pays."""
    PA, nA, PB, nB = ops
    o, j = idx // 4, idx % 4
    first, firstc, second, secondc = (PA, nA, PB, nB) if o == 0 else (PB, nB, PA, nA)
    M1 = first if j // 2 == 0 else firstc
    M2 = second if j % 2 == 0 else secondc
    return A.to_units(_norm2(A, _matvec(A, M2, _matvec(A, M1, psi, d, native), d, native), d, native))


def compile_ops(A, d, gs, ga, gb, commuting=False):
    """compile the served state and the four projector matrices from the stored angles (charged at compile time)."""
    psi = _state(A, d, gs)
    UA = _frame(A, d, ga, PLANES_A[d])
    PA = _proj(A, UA, KEEP_A[d], d)
    PB = _proj(A, UA, KEEP_B_COMMUTING[d], d) if commuting else _proj(A, _frame(A, d, gb, PLANES_B[d]), KEEP_A[d], d)
    return psi, (PA, _complement(A, PA, d), PB, _complement(A, PB, d))


def qq_residual(p):
    """QQ equality: P(A then B, yy) + P(notA then notB, both) - P(B then A, yy) - P(notB then notA, both)."""
    return p[0] + p[3] - p[4] - p[7]


def model_probs(A, d, gs, ga, gb, native, commuting=False):
    psi = _state(A, d, gs)
    UA = _frame(A, d, ga, PLANES_A[d])
    PA = _proj(A, UA, KEEP_A[d], d)
    if commuting:
        PB = _proj(A, UA, KEEP_B_COMMUTING[d], d)
    else:
        PB = _proj(A, _frame(A, d, gb, PLANES_B[d]), KEEP_A[d], d)
    return joint_probs(A, d, psi, PA, PB, native)


