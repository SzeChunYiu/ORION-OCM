def crossovers(adm, price):
    out = {}; names = sorted(adm); nat = price == "native"
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            ra, rb = adm[a], adm[b]
            fa = ra["desc_bits"] + (0 if nat else ra["learn_ops"]); fb = rb["desc_bits"] + (0 if nat else rb["learn_ops"])
            pa = ra["native_per_query"] if nat else ra["exec_per_query"]; pb = rb["native_per_query"] if nat else rb["exec_per_query"]
            if pa == pb: continue
            h = (fb - fa) / (pa - pb)
            if h > 0: out[f"{a}|{b}"] = round(h, 4)
    return out


def grid_for(cross, base=(1, 16, 128, 1024)):
    g = set(base)
    for h in cross.values():
        g.add(max(1, int(math.floor(h)))); g.add(int(math.ceil(h)) + 1); g.add(2 * int(math.ceil(h)) + 2)
    return sorted(g)


