BAYES_CENSUS_DEN = 6


def qq_census(n, precision="wide"):
    d = 2 ** n
    M = Machine(bases.ALL["B0_LOCAL_ADAPTIVE_TRANSDUCERS"]); A = QArith(M, precision); native = [0]
    proj = []
    for gs in range(G_ANGLES):
        for ga in range(G_ANGLES):
            for gb in range(G_ANGLES):
                proj.append(abs(qq_residual(model_probs(A, d, gs, ga, gb, native))))
    com = []
    for gs in range(G_ANGLES):
        for ga in range(G_ANGLES):
            com.append(abs(qq_residual(model_probs(A, d, gs, ga, ga, native, commuting=True))))
    bay = []
    U = PROB_UNITS
    for a in BAYES_CENSUS_GRID:
        for u in BAYES_CENSUS_GRID:
            for v in BAYES_CENSUS_GRID:
                for b in BAYES_CENSUS_GRID:
                    for x in BAYES_CENSUS_GRID:
                        for y in BAYES_CENSUS_GRID:
                            D = BAYES_CENSUS_DEN
                            r = (a * u + (D - a) * (D - v) - b * x - (D - b) * (D - y)) * U // (D * D)
                            bay.append(abs(r))
    return {"projective_family_size": len(proj), "projective_max_abs_qq_units": max(proj),
            "projective_frac_violating_tol": round(sum(1 for x in proj if x > TOL_UNITS) / len(proj), 6),
            "commuting_family_size": len(com), "commuting_max_abs_qq_units": max(com),
            "commuting_frac_violating_tol": round(sum(1 for x in com if x > TOL_UNITS) / len(com), 6),
            "ordered_bayes_family_size": len(bay), "ordered_bayes_max_abs_qq_units": max(bay),
            "ordered_bayes_frac_violating_tol": round(sum(1 for x in bay if x > TOL_UNITS) / len(bay), 6),
            "ordered_bayes_frac_exactly_zero": round(sum(1 for x in bay if x == 0) / len(bay), 6),
            "census_charged_ops": dict(M.L.c)}


