def compose_profiles(p: Profile, q: Profile) -> Profile:
    """Minimal antichain of {J u K : J in p, K in q}."""
    return rcl.canonical_profile(j | k for j in p for k in q)


def compose_profiles_b(p: Profile, q: Profile) -> Profile:
    """Independently written: enumerate unions, drop supersets by explicit scan."""
    unions = {frozenset(j) | frozenset(k) for j in p for k in q}
    minimal = [u for u in unions if not any(v < u for v in unions)]
    return tuple(sorted(minimal, key=lambda w: (len(w), sorted(w))))


# ----------------------------------------------------------------------------
# Representation revision: coarsening E by a partition
# ----------------------------------------------------------------------------

Partition = tuple[frozenset[Atom], ...]


def set_partitions(items: Sequence[Atom]) -> list[Partition]:
    if not items:
        return [()]
    first, rest = items[0], items[1:]
    out: list[Partition] = []
    for part in set_partitions(rest):
        out.append((frozenset({first}),) + part)
        for i, block in enumerate(part):
            out.append(part[:i] + (block | {first},) + part[i + 1 :])
    return [tuple(sorted(p, key=lambda b: sorted(b))) for p in out]


def is_block_union(r: frozenset[Atom], pi: Partition) -> bool:
    return all(block <= r or not (block & r) for block in pi)


def is_block_union_b(r: frozenset[Atom], pi: Partition) -> bool:
    """Independently written measurability test used by the S4 census, so that a
    mutation of ``is_block_union`` (which the coarse store consults) is detected
    against a judge it did not corrupt: a block is split iff it meets ``r`` in
    a proper nonempty subset."""
    for block in pi:
        k = len(block & r)
        if 0 < k < len(block):
            return False
    return True


def coarse_live(profile: Profile, r: frozenset[Atom], pi: Partition, policy: str) -> bool | None:
    """Liveness a coarse store can compute.  If ``r`` is a block union the answer is
    exact.  Otherwise the store must choose: ``over`` revokes every touched block
    (may falsely retract), ``under`` revokes only fully covered blocks (may falsely
    retain), ``abstain`` returns None."""
    if is_block_union(r, pi):
        return rcl.live(profile, r)
    if policy == "abstain":
        return None
    if policy == "over":
        rr = frozenset(a for block in pi if block & r for a in block)
    elif policy == "under":
        rr = frozenset(a for block in pi if block <= r for a in block)
    else:
        raise CannotCheck(f"unknown coarse policy {policy}")
    return rcl.live(profile, rr)


def partition_generated_by(gamma: Sequence[frozenset[Atom]], n: int) -> Partition:
    """Coarsest partition of E for which every R in gamma is a block union: atoms
    are in the same block iff no R separates them."""
    blocks: dict[tuple[bool, ...], set[Atom]] = {}
    for a in range(n):
        key = tuple(a in r for r in gamma)
        blocks.setdefault(key, set()).add(a)
    return tuple(sorted((frozenset(b) for b in blocks.values()), key=lambda b: sorted(b)))


def is_coarser_or_equal(pi: Partition, rho: Partition) -> bool:
    """pi is coarser than or equal to rho: every rho-block lies inside a pi-block."""
    return all(any(rb <= pb for pb in pi) for rb in rho)


