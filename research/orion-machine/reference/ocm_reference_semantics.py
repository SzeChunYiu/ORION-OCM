def _fresh(n: int) -> Substrate:
    return Substrate(n=n)


def check_S1_admission(n: int = 4) -> dict[str, object]:
    s = _fresh(n)
    beh = (0, 1, 2, 3)
    cert_ok = {"behaviour": beh, "warrants": [[0, 1], [2]]}
    cert_bad = {"behaviour": (9, 9, 9, 9), "warrants": [[0]]}
    s.admit("good", beh, cert_ok, "instruction", frozenset({"c1"}))
    s.admit("bad", beh, cert_bad, "instruction", frozenset({"c1"}))
    s.admit("laundered", beh, cert_bad, "instruction", frozenset({"c1"}), launder=True)
    invariant_violations = [r.name for r in s.records.values() if not r.checked_by_V]
    return {
        "admitted": sorted(s.records),
        "rejected_by_V": "bad" not in s.records,
        "laundering_planted": "laundered" in s.records,
        "laundering_caught_by_invariant": invariant_violations == ["laundered"],
        "V_calls": s.resources.V_cost,
        "holds": ("good" in s.records) and ("bad" not in s.records) and invariant_violations == ["laundered"],
    }


def check_S2_composition(n_exhaustive: int = 3, n_sampled: int = 4, samples: int = 4000, seed: int = 20260904) -> dict[str, object]:
    out: dict[str, object] = {}
    # exhaustive at n=3
    profiles = rcl.enumerate_antichains(n_exhaustive)
    revs = [frozenset(r) for k in range(n_exhaustive + 1) for r in itertools.combinations(range(n_exhaustive), k)]
    pairs = 0
    checks = 0
    bad: list[dict[str, object]] = []
    for p in profiles:
        for q in profiles:
            pairs += 1
            c = compose_profiles(p, q)
            if c != compose_profiles_b(p, q):
                bad.append({"p": p, "q": q, "reason": "two composition routines disagree"})
            for r in revs:
                checks += 1
                if rcl.live(c, r) != (rcl.live(p, r) and rcl.live(q, r)):
                    bad.append({"p": p, "q": q, "r": sorted(r), "reason": "liveness not conjunctive"})
    out["exhaustive"] = {"n": n_exhaustive, "antichains": len(profiles), "pairs": pairs, "liveness_checks": checks, "violations": bad[:3], "holds": not bad}
    # sampled at n=4
    rng = random.Random(seed)
    profiles4 = rcl.enumerate_antichains(n_sampled)
    revs4 = [frozenset(r) for k in range(n_sampled + 1) for r in itertools.combinations(range(n_sampled), k)]
    bad4: list[dict[str, object]] = []
    for _ in range(samples):
        p, q = rng.choice(profiles4), rng.choice(profiles4)
        c = compose_profiles(p, q)
        if c != compose_profiles_b(p, q):
            bad4.append({"reason": "routines disagree"})
        for r in revs4:
            if rcl.live(c, r) != (rcl.live(p, r) and rcl.live(q, r)):
                bad4.append({"reason": "liveness not conjunctive"})
    out["sampled"] = {"n": n_sampled, "antichains": len(profiles4), "pairs": samples, "seed": seed, "liveness_checks": samples * len(revs4), "violations": bad4[:3], "holds": not bad4}
    # scope intersection with a countermodel for union scope
    s = _fresh(n_sampled)
    s.admit("p", (0, 1, 2, 3), {"behaviour": (0, 1, 2, 3), "warrants": [[0]]}, "instruction", frozenset({"a", "b"}))
    s.admit("q", (0, 1, 2, 3), {"behaviour": (0, 1, 2, 3), "warrants": [[1]]}, "demonstration", frozenset({"b", "c"}))
    comp = s.compose("pq", "p", "q")
    union_scope = s.records["p"].scope | s.records["q"].scope
    countermodels = sorted(union_scope - comp.scope)
    out["scope"] = {"composite_scope": sorted(comp.scope), "union_scope_countermodels": countermodels, "holds": comp.scope == frozenset({"b"}) and countermodels == ["a", "c"]}
    out["holds"] = bool(out["exhaustive"]["holds"] and out["sampled"]["holds"] and out["scope"]["holds"])
    return out


def check_S3_revocation_completeness(n: int = 4) -> dict[str, object]:
    profiles = rcl.enumerate_antichains(n)
    revs = [frozenset(r) for k in range(n + 1) for r in itertools.combinations(range(n), k)]
    # complete store: every profile admitted through experimentation (closure certificate)
    s = _fresh(n)
    for i, p in enumerate(profiles):
        s.admit(f"r{i}", (i % 8,), {"behaviour": (i % 8,), "warrants": [sorted(w) for w in p]}, "experimentation", frozenset({"c"}))
    checks = 0
    mismatches = 0
    agreement_two_evaluators = 0
    for r in revs:
        got = s.live_set(r)
        for i, p in enumerate(profiles):
            checks += 1
            expect = rcl.live(p, r)
            if got[f"r{i}"] != expect:
                mismatches += 1
            if rcl.live(p, r) == rcl.live_via_active_set(p, r, n):
                agreement_two_evaluators += 1
    # planted positive-only store: keeps one witness (first warrant) per record, RCL-2b
    s1 = _fresh(n)
    over_retractions = 0
    abstentions = 0
    witness = None
    for i, p in enumerate(profiles):
        if not p:
            continue
        one = [sorted(p[0])]
        s1.admit(f"r{i}", (i % 8,), {"behaviour": (i % 8,), "warrants": one}, "instruction", frozenset({"c"}))
    for r in revs:
        got = s1.live_set(r)
        for i, p in enumerate(profiles):
            if not p:
                continue
            truth = rcl.live(p, r)
            g = got[f"r{i}"]
            if truth and g is None:
                abstentions += 1
                if witness is None:
                    witness = {"profile": [sorted(w) for w in p], "revoked": sorted(r), "emitted_witness": sorted(p[0])}
            if truth and g is False:
                over_retractions += 1
    return {
        "n": n,
        "antichains": len(profiles),
        "revocations": len(revs),
        "liveness_checks": checks,
        "mismatches": mismatches,
        "two_evaluator_agreement": {"agree": agreement_two_evaluators, "denominator": checks},
        "planted_positive_only_store": {
            "false_retractions": over_retractions,
            "abstentions_where_truth_is_live": abstentions,
            "first_witness": witness,
            "caught": abstentions > 0 and over_retractions == 0,
            "reading": "a positive-only record whose emitted witness dies must abstain, never retract (RCL-2b); the substrate abstains",
        },
        "holds": mismatches == 0 and agreement_two_evaluators == checks and abstentions > 0 and over_retractions == 0,
    }


def check_S4_representation_revision(n: int = 4) -> dict[str, object]:
    profiles = rcl.enumerate_antichains(n)
    partitions = set_partitions(list(range(n)))
    gammas = {
        "singletons": [frozenset({a}) for a in range(n)],
        "pairs_01_23": [frozenset({0, 1}), frozenset({2, 3})],
        "nested_0_01_012": [frozenset({0}), frozenset({0, 1}), frozenset({0, 1, 2})],
        "one_set_12": [frozenset({1, 2})],
    }
    rows: list[dict[str, object]] = []
    all_ok = True
    for gname, gamma in gammas.items():
        generated = partition_generated_by(gamma, n)
        exact_partitions: list[Partition] = []
        for pi in partitions:
            # measurability judged by the independently written test, never by the
            # function the coarse store itself consults
            measurable = all(is_block_union_b(r, pi) for r in gamma)
            # exactness of each *committed* policy, evaluated on every profile and
            # every admitted revocation; abstention is counted separately because an
            # abstaining store is honest, not exact
            exact_over = all(coarse_live(p, r, pi, "over") == rcl.live(p, r) for p in profiles for r in gamma)
            exact_under = all(coarse_live(p, r, pi, "under") == rcl.live(p, r) for p in profiles for r in gamma)
            abstains = sum(1 for p in profiles for r in gamma if coarse_live(p, r, pi, "abstain") is None)
            if exact_over != measurable or exact_under != measurable:
                all_ok = False
            if (abstains == 0) != measurable:
                all_ok = False
            if exact_over and exact_under:
                exact_partitions.append(pi)
        coarsest_is_generated = generated in exact_partitions and all(is_coarser_or_equal(generated, pi) for pi in exact_partitions)
        if not coarsest_is_generated:
            all_ok = False
        rows.append({
            "gamma": gname,
            "partitions_examined": len(partitions),
            "exact_partitions": len(exact_partitions),
            "generated_partition": [sorted(b) for b in generated],
            "generated_is_coarsest_exact": coarsest_is_generated,
            "policies_evaluated": ["over", "under"],
            "abstain_counted_separately": True,
        })
    # planted: merge atoms 1 and 2 while gamma separates them (R = {1}); must produce a witness
    pi_bad: Partition = (frozenset({0}), frozenset({1, 2}), frozenset({3}))
    r = frozenset({1})
    false_retract = None
    false_retain = None
    for p in profiles:
        truth = rcl.live(p, r)
        if truth and coarse_live(p, r, pi_bad, "over") is False and false_retract is None:
            false_retract = {"profile": [sorted(w) for w in p], "revoked": [1]}
        if (not truth) and coarse_live(p, r, pi_bad, "under") is True and false_retain is None:
            false_retain = {"profile": [sorted(w) for w in p], "revoked": [1]}
    planted_caught = false_retract is not None and false_retain is not None
    if not planted_caught:
        all_ok = False
    return {
        "n": n,
        "antichains": len(profiles),
        "partitions": len(partitions),
        "families": rows,
        "planted_split_coarsening": {"partition": [sorted(b) for b in pi_bad], "false_retract_witness": false_retract, "false_retain_witness": false_retain, "caught": planted_caught},
        "holds": all_ok,
    }


def check_S5_strategy_revision(n: int = 4) -> dict[str, object]:
    profiles = rcl.enumerate_antichains(n)
    revs = [frozenset(r) for k in range(n + 1) for r in itertools.combinations(range(n), k)]
    s = _fresh(n)
    for i, p in enumerate(profiles):
        if p:
            s.admit(f"r{i}", (i % 8,), {"behaviour": (i % 8,), "warrants": [sorted(w) for w in p]}, "experimentation", frozenset({"c"}))
    before = {name: tuple(s.live(name, r) for r in revs) for name in s.records}
    # strategy swap: from now on admit through demonstration; already-admitted records untouched
    s.admit("new", (7,), {"behaviour": (7,), "warrants": [[0]]}, "demonstration", frozenset({"c"}))
    after = {name: tuple(s.live(name, r) for r in revs) for name in before}
    unchanged = sum(1 for k in before if before[k] == after[k])
    # planted: a policy that re-admits an existing record through feedback (endpoint) — loses its warrant
    s_bad = _fresh(n)
    s_bad.admit("r", (1,), {"behaviour": (1,), "warrants": [[0], [1]]}, "experimentation", frozenset({"c"}))
    sig_before = tuple(s_bad.live("r", r) for r in revs)
    s_bad.admit("r", (1,), {"behaviour": (1,)}, "feedback", frozenset({"c"}))
    sig_after = tuple(s_bad.live("r", r) for r in revs)
    return {
        "records": len(before),
        "revocations": len(revs),
        "signatures_unchanged": unchanged,
        "planted_readmission_under_weaker_channel": {"before": sig_before, "after": sig_after, "caught": sig_before != sig_after},
        "holds": unchanged == len(before) and sig_before != sig_after,
    }


def check_S6_architecture_revision(n: int = 4) -> dict[str, object]:
    profiles = rcl.enumerate_antichains(n)
    table = {rcl.signature(p, n): p for p in profiles}
    injective = len(table) == len(profiles)
    roundtrip = sum(1 for p in profiles if decode_signature(encode_signature(p, n), n, table) == p)
    dropped = {}
    collisions = 0
    for p in profiles:
        k = encode_dropping_last(p, n)
        if k in dropped:
            collisions += 1
        dropped[k] = p
    return {
        "n": n,
        "antichains": len(profiles),
        "signature_injective": injective,
        "roundtrip_exact": roundtrip,
        "planted_encoding_dropping_last_coordinate": {"distinct_codes": len(dropped), "collisions": collisions, "caught": collisions > 0},
        "holds": injective and roundtrip == len(profiles) and collisions > 0,
    }


def check_S7_resource_conservation(n: int = 4) -> dict[str, object]:
    s = _fresh(n)
    deltas: list[dict[str, object]] = []

    def step(label: str, fn: Callable[[], object], charged: str) -> None:
        before = s.resources.as_tuple()
        dig_before = store_digest(s.records)
        fn()
        after = s.resources.as_tuple()
        dig_after = store_digest(s.records)
        names = ("B_theta", "B_mut", "V_cost", "Q_queries", "W_update", "recourse", "abstentions")
        d = {k: a - b for k, a, b in zip(names, after, before, strict=True)}
        deltas.append({"op": label, "delta": d, "store_changed": dig_before != dig_after, "charged": charged, "charged_positive": d[charged] > 0, "B_theta_constant": d["B_theta"] == 0})

    step("admit/instruction", lambda: s.admit("a", (1,), {"behaviour": (1,), "warrants": [[0], [1, 2]]}, "instruction", frozenset({"c"})), "V_cost")
    step("admit/interaction", lambda: s.admit("b", (2,), {"behaviour": (2,), "warrants": [[3]], "queries": 4}, "interaction", frozenset({"c"})), "Q_queries")
    step("compose", lambda: s.compose("ab", "a", "b"), "B_mut")
    step("revoke{3}", lambda: s.revoke({3}), "W_update")
    honest_ok = all(d["charged_positive"] and d["B_theta_constant"] for d in deltas)
    revoke_delta = deltas[-1]["delta"]
    honest_ok = honest_ok and revoke_delta["recourse"] == 2 and revoke_delta["W_update"] == 3  # b and ab reopen; three records re-evaluated
    # planted: a "free" transition that mutates the store without charging any counter
    dig_before = store_digest(s.records)
    before = s.resources.as_tuple()
    s.records["a"] = replace(s.records["a"], profile=())
    free = {"store_changed": store_digest(s.records) != dig_before, "any_counter_changed": s.resources.as_tuple() != before}
    free["caught"] = free["store_changed"] and not free["any_counter_changed"]
    return {"transitions": deltas, "planted_free_mutation": free, "holds": honest_ok and free["caught"]}


