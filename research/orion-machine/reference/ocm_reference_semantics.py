Atom = int
Warrant = frozenset[Atom]
Profile = tuple[Warrant, ...]
Scope = frozenset[str]

CHANNELS: tuple[str, ...] = ("instruction", "demonstration", "interaction", "experimentation", "feedback")

# What warrant each channel's certificate kind can carry.  This is the substrate's
# only commitment about channels: it fixes *what is warranted*, not how it is learned.
#   positive  -> the certificate exhibits at least one full warrant (a checked proof / trace);
#   closure   -> the certificate additionally certifies that the listed warrants are all of them;
#   endpoint  -> the certificate only fixes behaviour; no warrant is exhibited (feedback);
#   query     -> interaction answers liveness queries; warrants are assembled from answers.
CHANNEL_CERTIFICATE_KIND: dict[str, str] = {
    "instruction": "positive",
    "demonstration": "positive",
    "interaction": "query",
    "experimentation": "closure",
    "feedback": "endpoint",
}


