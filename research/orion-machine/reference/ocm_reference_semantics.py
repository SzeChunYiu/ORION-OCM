def mutation_controls(n: int = 4) -> dict[str, object]:
    out: dict[str, object] = {}
    # M1: composition that takes intersections instead of unions -> S2 liveness conjunction fails
    orig = compose_profiles
    witness_p, witness_q = (frozenset({0}),), (frozenset({1}),)

    def bad_compose(p: Profile, q: Profile) -> Profile:
        return rcl.canonical_profile(j & k for j in p for k in q)

    applied = bad_compose(witness_p, witness_q) != orig(witness_p, witness_q)
    globals()["compose_profiles"] = bad_compose
    try:
        res = check_S2_composition(samples=200)
    finally:
        globals()["compose_profiles"] = orig
    out["M1_compose_by_intersection"] = {"applied": applied, "detected": not res["holds"], "registered_reason": "S2 liveness must stop being conjunctive"}

    # M2: liveness that ignores revocation -> S3 mismatches, and the two evaluators disagree
    orig_live = rcl.live
    applied2 = orig_live((frozenset({0}),), frozenset({0})) is False

    def bad_live(profile: Profile, revoked: Iterable[Atom]) -> bool:
        return bool(profile)

    applied2 = applied2 and bad_live((frozenset({0}),), frozenset({0})) is True
    rcl.live = bad_live
    try:
        res3 = check_S3_revocation_completeness(n)
    finally:
        rcl.live = orig_live
    out["M2_live_ignores_revocation"] = {"applied": applied2, "detected": not res3["holds"], "two_evaluator_agreement": res3["two_evaluator_agreement"], "registered_reason": "the two evaluators must disagree and the completeness invariant must fail"}

    # M3: block-union test that always says True -> S4 exactness != measurability
    orig_bu = is_block_union
    applied3 = orig_bu(frozenset({1}), (frozenset({0}), frozenset({1, 2}), frozenset({3}))) is False
    globals()["is_block_union"] = lambda r, pi: True
    try:
        res4 = check_S4_representation_revision(n)
    finally:
        globals()["is_block_union"] = orig_bu
    # registered reason: with the store's block-union test corrupted, the committed
    # policies report exact answers on split partitions, so exactness disagrees with
    # the independent measurability judge on at least one (partition, family)
    m3_reason_fires = any(
        r["exact_partitions"] != {"singletons": 1, "pairs_01_23": 4, "nested_0_01_012": 1, "one_set_12": 4}[r["gamma"]]
        for r in res4["families"]
    )
    out["M3_block_union_always_true"] = {"applied": applied3, "detected": (not res4["holds"]) and m3_reason_fires, "exact_partition_counts_under_mutation": {r["gamma"]: r["exact_partitions"] for r in res4["families"]}, "registered_reason": "S4 exactness must disagree with the independent measurability judge (exact-partition counts change)"}

    # M4: resource counter that never charges V -> S7 charged_positive fails
    orig_V = Substrate.V

    def free_V(self, behaviour, certificate):  # type: ignore[no-untyped-def]
        return orig_V(self, behaviour, certificate) if False else certificate.get("behaviour") == behaviour

    probe = _fresh(n)
    free_V(probe, (1,), {"behaviour": (1,)})
    applied4 = probe.resources.V_cost == 0
    Substrate.V = free_V  # type: ignore[method-assign]
    try:
        res7 = check_S7_resource_conservation(n)
    finally:
        Substrate.V = orig_V  # type: ignore[method-assign]
    out["M4_checker_not_charged"] = {"applied": applied4, "detected": not res7["holds"], "registered_reason": "admission must charge V_cost"}
    out["planted"] = 4
    out["detected"] = sum(1 for k, v in out.items() if isinstance(v, dict) and v.get("detected"))
    return out


