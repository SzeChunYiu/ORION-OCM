#!/usr/bin/env python3
"""Lane #203 — executable reference semantics of the minimal OCM substrate.

Operator directive (#194, comment 5539487737, 2026-09-04): the object of study is
the *substrate + constraints*, not an architecture.  This module is the substrate
as a finite labelled transition system whose every transition is exact and whose
constraints are checked exhaustively at small evidence size.  It authorizes no
architecture, novelty, language, quantum or superiority claim.

Substrate ``Sigma = (E, Store, V, Ch, compose, revoke, revise, R)``:

* ``E = {0..n-1}``          finite evidence atoms (the things that can later be revoked);
* ``Store``                 named records, each ``(behaviour, profile, scope, epoch, channel)``
                            where ``profile`` is an antichain of inclusion-minimal
                            sufficient warrants over ``E`` (the RCL formal object of
                            ``revocation_complete_learning/rcl_model.py``, imported, not
                            re-implemented, so the checked object is the committed one);
* ``V``                     the checker: a record enters the store *live* only if ``V``
                            accepts its certificate against its behaviour (admission
                            gate; laundering = entering without ``V``);
* ``Ch``                    the five acquisition channels of the directive — instruction,
                            demonstration, interaction, experimentation, feedback — each
                            an admission path that produces a certificate of a stated
                            *kind*; the substrate does not fix a learning algorithm, it
                            fixes what warrant each kind can carry;
* ``compose``               skill composition with warrant preserved (Theorem S2);
* ``revoke``                evidence revocation ``R subset E`` (the RCL constraint, S3);
* ``revise``                self-revision: representation (coarsening of ``E``), learning
                            strategy (admission policy), architecture (store encoding);
                            each must preserve exact authority over what is already
                            known (S4, S5, S6);
* ``R``                     whole-system resource counters (#194 section 4), with the
                            conservation check S7.

Constraints checked exhaustively (every count carries its denominator):

  S1  admission soundness: every live record was admitted through ``V`` and ``V``
      accepted; a planted laundering path is caught;
  S2  composition: the composite's profile is the minimal antichain of unions
      ``J u K``; its liveness is the conjunction; its scope is the intersection;
      checked over all antichain pairs at n=3 (20 x 20) and all revocations, and
      over 4,000 sampled pairs at n=4 with a fixed seed;
  S3  revocation completeness: after ``revoke(R)`` the live set equals the set
      computed from the full profiles; a planted positive-only store (one witness
      per record, RCL-2b) is caught with the over-retraction witness;
  S4  representation revision: a coarsening ``pi`` of ``E`` under a *committed*
      policy (``over``: revoke every touched block; ``under``: revoke only covered
      blocks) answers every ``R`` in the admitted family ``Gamma`` exactly iff every
      ``R`` is a union of ``pi``-blocks -- each direction evaluated on every profile,
      with the ``abstain`` policy counted separately (an abstaining store is honest,
      not exact) and measurability judged by an independently written test; the
      coarsest such ``pi`` is the partition generated by ``Gamma``; a planted
      coarsening that splits some ``R`` produces a false-retain or false-retract
      witness (checked over all 15 partitions of 4 atoms x registered ``Gamma``).
      A first draft scored ``abstain`` inside the exactness loop, which made
      ``exact`` coincide with ``is_block_union`` by construction (VACUOUS_CONTRAST;
      found by Cursor Bugbot on PR #279 at e9a0222, repaired before merge);
  S5  strategy revision (admission-policy swap) leaves the liveness signature of
      every already-admitted record unchanged; a planted policy that re-admits a
      record under a weaker checker changes its status and is caught;
  S6  architecture revision (store re-encoding to the revocation signature and back)
      is authority-preserving because the signature determines the antichain
      (RCL-0); a planted encoding that drops one coordinate is caught;
  S7  resource conservation: every transition's counted-resource delta is
      non-negative and non-zero on the coordinate it charges (admission charges
      the checker, interaction charges queries, composition charges store bits,
      revocation charges revalidation work and records recourse); a planted
      "free" transition that mutates the store without charging is caught.

No-alarm controls compare two *independently written* liveness evaluators
(``rcl_model.live`` and ``rcl_model.live_via_active_set``) and two independently
written composition routines.  Mutation controls are asserted applied on a witness
*before* the check runs.  Exit contract of ``main``: ``0`` pass, ``1`` a check failed
for its registered reason, ``2`` ``CANNOT_CHECK`` (never a pass).

Parents (see theory/OCM_OPERATIONAL_SEMANTICS_V1.md): the profile is an ATMS label
(de Kleer 1986); admission is proof-carrying code (Necula 1997); S3 is
dependency-directed truth maintenance (Doyle 1979); S4 is Blackwell sufficiency /
lane-201 L1; S6 is RCL-0; S7 is the full-system honesty rule of #194 section 4.
"""

