@dataclass(frozen=True)
class Record:
    name: str
    behaviour: tuple[int, ...]
    profile: Profile  # canonical antichain over E
    scope: Scope
    epoch: int
    channel: str
    certificate_kind: str
    checked_by_V: bool
    complete: bool  # True iff the profile is certified complete (closure); False = positive-only


@dataclass
class Resources:
    """#194 section 4 vector, restricted to the coordinates this substrate has."""

    B_theta: int  # immutable substrate description (constant; the interpreter)
    B_mut: int = 0  # store bits
    V_cost: int = 0  # checker calls
    Q_queries: int = 0  # interaction queries
    W_update: int = 0  # records re-evaluated by a revocation (revalidation work)
    recourse: int = 0  # records whose status changed under revocation/revision
    abstentions: int = 0

    def as_tuple(self) -> tuple[int, ...]:
        return (self.B_theta, self.B_mut, self.V_cost, self.Q_queries, self.W_update, self.recourse, self.abstentions)


def store_bits(records: dict[str, Record], n: int) -> int:
    # one bit per atom per warrant plus one bit per record for the completeness flag
    return sum(len(r.profile) * n + 1 for r in records.values())


def store_digest(records: dict[str, Record]) -> str:
    payload = sorted((r.name, r.behaviour, tuple(sorted(tuple(sorted(w)) for w in r.profile)), tuple(sorted(r.scope)), r.epoch, r.complete) for r in records.values())
    return hashlib.sha256(repr(payload).encode()).hexdigest()


@dataclass
class Substrate:
    n: int
    records: dict[str, Record] = field(default_factory=dict)
    revoked: frozenset[Atom] = frozenset()
    epoch: int = 0
    resources: Resources = field(default_factory=lambda: Resources(B_theta=SUBSTRATE_DESCRIPTION_BITS))
    log: list[dict[str, object]] = field(default_factory=list)

    # ---- the checker V -----------------------------------------------------
    def V(self, behaviour: tuple[int, ...], certificate: dict[str, object]) -> bool:
        """Accept iff the certificate's exhibited warrants are well-formed over E and
        its claimed behaviour equals the behaviour being admitted.  Deliberately
        minimal: V checks the certificate, it does not solve the task (#194 C7)."""
        self.resources.V_cost += 1
        if certificate.get("behaviour") != behaviour:
            return False
        for w in certificate.get("warrants", ()):
            if not all(0 <= a < self.n for a in w):
                return False
        return True

    # ---- admission through a channel --------------------------------------
    def admit(self, name: str, behaviour: tuple[int, ...], certificate: dict[str, object], channel: str, scope: Scope, *, launder: bool = False) -> Record:
        if channel not in CHANNELS:
            raise CannotCheck(f"unknown channel {channel}")
        kind = CHANNEL_CERTIFICATE_KIND[channel]
        warrants = tuple(frozenset(w) for w in certificate.get("warrants", ()))
        if kind == "endpoint":
            warrants = ()  # feedback fixes behaviour only; no warrant is exhibited
        if kind == "query":
            self.resources.Q_queries += int(certificate.get("queries", 0))
        accepted = True if launder else self.V(behaviour, certificate)
        profile = rcl.canonical_profile(warrants) if warrants else ()
        rec = Record(
            name=name,
            behaviour=behaviour,
            profile=profile,
            scope=scope,
            epoch=self.epoch,
            channel=channel,
            certificate_kind=kind,
            checked_by_V=not launder,
            complete=(kind == "closure") and accepted,
        )
        if accepted:
            self.records[name] = rec
        self.resources.B_mut = store_bits(self.records, self.n)
        self.log.append({"op": "admit", "name": name, "channel": channel, "accepted": accepted, "laundered": launder})
        return rec

    # ---- liveness ------------------------------------------------------------
    def live(self, name: str, revoked: Iterable[Atom] | None = None) -> bool | None:
        """True/False, or None = abstain (positive-only record whose exhibited
        warrants are all dead: absence of a live witness is not proof of absence)."""
        rec = self.records[name]
        rv = self.revoked if revoked is None else frozenset(revoked)
        if not rec.profile:
            # certified-empty (closure) = dead; endpoint-only = no warrant to evaluate
            return False if rec.complete else None
        if rcl.live(rec.profile, rv):
            return True
        return False if rec.complete else None

    def live_set(self, revoked: Iterable[Atom] | None = None) -> dict[str, bool | None]:
        return {name: self.live(name, revoked) for name in self.records}

    # ---- composition ---------------------------------------------------------
    def compose(self, name: str, left: str, right: str) -> Record:
        p, q = self.records[left], self.records[right]
        profile = compose_profiles(p.profile, q.profile)
        rec = Record(
            name=name,
            behaviour=tuple(b for pair in zip(p.behaviour, q.behaviour, strict=True) for b in pair),
            profile=profile,
            scope=p.scope & q.scope,
            epoch=self.epoch,
            channel="composition",
            certificate_kind="bridge",
            checked_by_V=p.checked_by_V and q.checked_by_V,
            complete=p.complete and q.complete,
        )
        self.records[name] = rec
        self.resources.B_mut = store_bits(self.records, self.n)
        self.log.append({"op": "compose", "name": name, "left": left, "right": right})
        return rec

    # ---- revocation ----------------------------------------------------------
    def revoke(self, atoms: Iterable[Atom]) -> dict[str, bool | None]:
        before = self.live_set()
        self.revoked = self.revoked | frozenset(atoms)
        self.epoch += 1
        after = self.live_set()
        reopened = [k for k in after if after[k] != before[k]]
        self.resources.W_update += len(after)
        self.resources.recourse += len(reopened)
        self.resources.abstentions += sum(1 for v in after.values() if v is None)
        self.log.append({"op": "revoke", "atoms": sorted(atoms), "reopened": reopened})
        return after


