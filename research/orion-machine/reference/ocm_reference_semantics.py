def run_reference_semantics(n: int = 4) -> dict[str, object]:
    t0 = time.perf_counter()
    if n > rcl.MAX_EXHAUSTIVE_N:
        raise CannotCheck(f"exhaustive antichain enumeration capped at n={rcl.MAX_EXHAUSTIVE_N}")
    checks = {
        "S1_admission": check_S1_admission(n),
        "S2_composition": check_S2_composition(),
        "S3_revocation_completeness": check_S3_revocation_completeness(n),
        "S4_representation_revision": check_S4_representation_revision(n),
        "S5_strategy_revision": check_S5_strategy_revision(n),
        "S6_architecture_revision": check_S6_architecture_revision(n),
        "S7_resource_conservation": check_S7_resource_conservation(n),
    }
    failed = [k for k, v in checks.items() if not v["holds"]]
    if failed:
        raise AssertionError(f"constraints failed: {failed}")
    muts = mutation_controls(n)
    if muts["detected"] != muts["planted"]:
        raise AssertionError(f"mutation controls: {muts['detected']}/{muts['planted']} detected")
    return {
        "schema": "orion.ocm.reference-semantics.exact-results.v1",
        "terminal": "PASS_SUBSTRATE_CONSTRAINTS_EXACT",
        "substrate": {
            "evidence_atoms": n,
            "channels": list(CHANNELS),
            "channel_certificate_kind": CHANNEL_CERTIFICATE_KIND,
            "profile_model": "revocation_complete_learning/rcl_model.py (imported, not re-implemented)",
            "B_theta_bits": SUBSTRATE_DESCRIPTION_BITS,
        },
        "checks": checks,
        "controls": {"mutations": muts, "M0_unmutated": {"applied": True, "all_checks_pass": True}},
        "runtime_seconds": round(time.perf_counter() - t0, 3),
        "authority": {
            "finite_model_only": True,
            "semantics_frozen": False,
            "proof_assistant_encoding": "CANNOT_CHECK: no toolchain provisioned",
            "novelty_established": False,
            "architecture_superiority_established": False,
        },
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = run_reference_semantics()
    except CannotCheck as exc:
        print(json.dumps({"terminal": "CANNOT_CHECK", "reason": str(exc)}, indent=2))
        return 2
    except AssertionError as exc:
        print(json.dumps({"terminal": "FAIL", "error": str(exc)}, indent=2))
        return 1
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True, default=str))
    else:
        c = result["checks"]
        print(
            f"PASS substrate constraints S1-S7 at n=4: S2 {c['S2_composition']['exhaustive']['liveness_checks']} exhaustive + "
            f"{c['S2_composition']['sampled']['liveness_checks']} sampled liveness checks; S3 {c['S3_revocation_completeness']['liveness_checks']} checks, "
            f"{c['S3_revocation_completeness']['mismatches']} mismatches; S4 {c['S4_representation_revision']['partitions']} partitions x "
            f"{len(c['S4_representation_revision']['families'])} families; S6 {c['S6_architecture_revision']['antichains']} antichains round-trip; "
            f"{result['controls']['mutations']['detected']}/{result['controls']['mutations']['planted']} mutations detected; {result['runtime_seconds']} s"
        )
    return 0


